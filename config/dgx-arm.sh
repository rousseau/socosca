#!/bin/bash
# =============================================================================
# config/dgx-arm.sh — DGX ARM, Linux ARM64 (aarch64), GPU NVIDIA CUDA
# Adapter les chemins selon l'installation réelle sur le DGX
# =============================================================================
export MACHINE_ID="dgx-arm"

# ---------------------------------------------------------------------------
# FreeSurfer — à adapter selon l'installation sur le DGX
# ---------------------------------------------------------------------------
export FREESURFER_HOME="${FREESURFER_HOME:-/usr/local/freesurfer/8.2.0}"
export FS_LICENSE="${FS_LICENSE:-${HOME}/.freesurfer_license.txt}"

# ---------------------------------------------------------------------------
# FSL
# ---------------------------------------------------------------------------
export FSLDIR="${FSLDIR:-/usr/local/fsl}"

# ---------------------------------------------------------------------------
# ANTs
# ---------------------------------------------------------------------------
export ANTS_BIN="${ANTS_BIN:-/usr/local/ants/bin}"

# ---------------------------------------------------------------------------
# MRtrix3
# ---------------------------------------------------------------------------
export MRTRIX_BIN="${MRTRIX_BIN:-/usr/local/bin}"

# ---------------------------------------------------------------------------
# SIAM — disponible sur DGX (GPU CUDA)
# ---------------------------------------------------------------------------
export SIAM_AVAILABLE=true
export SIAM_DEVICE="cuda"
# Adapter le chemin si SIAM est installé dans un env conda spécifique
export SIAM_CMD="${SIAM_CMD:-siam-pred}"

# ---------------------------------------------------------------------------
# Python
# ---------------------------------------------------------------------------
export PYTHON_CMD="${PYTHON_CMD:-python3}"

# ---------------------------------------------------------------------------
# Ressources
# ---------------------------------------------------------------------------
export NTHR_DEFAULT="${NTHR_DEFAULT:-16}"

# ---------------------------------------------------------------------------
# PATH
# ---------------------------------------------------------------------------
export PATH="${FREESURFER_HOME}/bin:${FSLDIR}/bin:${ANTS_BIN}:${MRTRIX_BIN}:${PATH}"
