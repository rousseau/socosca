#!/bin/bash
# =============================================================================
# config/macos.sh — MacBook Pro, macOS, Apple Silicon (ARM64)
# =============================================================================
export MACHINE_ID="macos"

# ---------------------------------------------------------------------------
# FreeSurfer
# ---------------------------------------------------------------------------
export FREESURFER_HOME="/Applications/freesurfer/8.2.0"

# Licence FreeSurfer — premier fichier trouvé
export FS_LICENSE=""
for _lic in \
    "${FREESURFER_HOME}/license.txt" \
    "${HOME}/Downloads/license.txt" \
    "${HOME}/Sync/license.txt" \
    "${HOME}/.freesurfer.txt"
do
    if [ -f "$_lic" ]; then
        export FS_LICENSE="$_lic"
        break
    fi
done

# ---------------------------------------------------------------------------
# FSL
# ---------------------------------------------------------------------------
export FSLDIR="${HOME}/fsl"

# ---------------------------------------------------------------------------
# ANTs
# ---------------------------------------------------------------------------
export ANTS_BIN="${HOME}/Code/ants-2.5.4/bin"

# ---------------------------------------------------------------------------
# MRtrix3  (installé dans /usr/local/bin sur macOS)
# ---------------------------------------------------------------------------
export MRTRIX_BIN="/usr/local/bin"

# ---------------------------------------------------------------------------
# SIAM
# ---------------------------------------------------------------------------
# SIAM requiert ~15 Go de VRAM GPU — non disponible sur ce MacBook
export SIAM_AVAILABLE=false
export SIAM_DEVICE="mps"
export SIAM_CMD="${HOME}/miniforge3/bin/siam-pred"

# ---------------------------------------------------------------------------
# Python
# ---------------------------------------------------------------------------
export PYTHON_CMD="python3"

# ---------------------------------------------------------------------------
# Ressources
# ---------------------------------------------------------------------------
export NTHR_DEFAULT=8

# ---------------------------------------------------------------------------
# PATH
# ---------------------------------------------------------------------------
export PATH="${FREESURFER_HOME}/bin:${FSLDIR}/bin:${ANTS_BIN}:${MRTRIX_BIN}:${PATH}"
